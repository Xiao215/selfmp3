/**
 * A stamp the build replaces, so each build's shell is its own cache.
 *
 * The shell holds hashed asset files, which a new build renames rather than
 * overwrites: under one fixed cache name, every build's superseded JavaScript
 * and CSS would stay on the device for good. Naming the cache after the build
 * means `activate` sweeps the last one away as part of what it already does.
 * Left as `dev` when nothing substitutes it — one cache it keeps reusing.
 */
declare const __SHELL_BUILD__: string
const SHELL_BUILD = typeof __SHELL_BUILD__ === 'string' ? __SHELL_BUILD__ : 'dev'

const SHELL_CACHE = `selfmp3-shell-${SHELL_BUILD}`
/*
 * The API and audio caches (./names.ts) are deliberately *not* named after the
 * build: what they hold is the person's, not this build's, and re-downloading
 * every song and cover on a deploy is unthinkable.
 */

/**
 * Caches this worker keeps, its own and the tab's. Anything else from an old
 * build gets deleted.
 */
const OWNED_CACHES = new Set([SHELL_CACHE, API_CACHE, AUDIO_CACHE, CLOUD_FILES_CACHE, PLAYED_CACHE])

/** `/` in the desktop app, `/selfmp3/` on GitHub Pages: this worker's scope. */
const BASE = new URL(self.registration.scope).pathname

/** Registered as `sw.js?cloud=1` when signed in to the cloud (src/ports/serviceWorker.web.ts): only then is there a bucket to ask. */
const CLOUD = new URL(self.location.href).searchParams.get('cloud') === '1'
const INDEX = `${BASE}index.html`

/**
 * The files of this export the shell keeps besides the page, as paths under
 * the scope: written beside the worker by scripts/shell.mjs at export. Absent
 * for a worker built on its own, which then keeps the page alone.
 */
const SHELL_LIST = `${BASE}shell.json`

self.addEventListener('install', event => {
  event.waitUntil(
    (async () => {
      await keepShell()
      // Take over immediately; waiting for every tab to close is not the
      // behaviour anyone wants from their own music app.
      await self.skipWaiting()
    })(),
  )
})

/**
 * Keep this build's page and every file it loads, before taking over.
 *
 * All of it, at install. Kept as the page asked for them, the bundle was
 * never kept at all on a first visit (the page that loads it is not this
 * worker's yet) and, after a deploy, was kept by the old worker into the old
 * build's cache, which `activate` sweeps — either way the next offline open
 * was a blank page. A file that cannot be fetched fails the install, and the
 * browser tries again on a later visit: the worker before this one, and its
 * whole shell, stay until then.
 *
 * The page and the list are asked for past the browser's HTTP cache (Pages
 * says ten minutes), which would otherwise hand over the last build's page.
 * The rest are named after their contents, so a copy the last build kept is
 * the same file and is taken from there.
 */
async function keepShell(): Promise<void> {
  const cache = await caches.open(SHELL_CACHE)
  const fresh = (url: string) => new Request(url, { cache: 'no-cache' })
  await cache.add(fresh(INDEX))
  // Wanted, but not the app: a missing manifest does not fail the install.
  await cache.add(fresh(`${BASE}manifest.webmanifest`)).catch(() => undefined)
  const listed = await fetch(fresh(SHELL_LIST)).catch(() => null)
  const files: unknown = listed?.ok ? await listed.json() : []
  if (!Array.isArray(files)) return
  await Promise.all(
    files
      .filter((file): file is string => typeof file === 'string')
      .map(async file => {
        const url = `${BASE}${file}`
        const kept = await caches.match(url)
        await (kept ? cache.put(url, kept) : cache.add(url))
      }),
  )
}

self.addEventListener('activate', event => {
  event.waitUntil(
    (async () => {
      const names = await caches.keys()
      await Promise.all(
        names
          .filter(name => name.startsWith('selfmp3-') && !OWNED_CACHES.has(name))
          .map(name => caches.delete(name)),
      )
      await self.clients.claim()
    })(),
  )
})

self.addEventListener('message', event => {
  const data: unknown = event.data
  if (typeof data === 'object' && data !== null && 'type' in data) {
    const { type } = data as { type: string }
    // A page loaded around this worker, by a hard reload, asking to be answered
    // for after all (src/ports/serviceWorker.web.ts).
    if (type === SW_MESSAGE.claim) event.waitUntil(self.clients.claim())
    // The cap raised at backblaze.com, says the person: ask the bucket again.
    if (type === SW_MESSAGE.release) capped = null
  }
})

self.addEventListener('fetch', event => {
  const request = event.request
  if (request.method !== 'GET' && request.method !== 'HEAD') return

  const url = new URL(request.url)
  // Never touch cross-origin requests (album art from a thumbnail host, etc).
  if (url.origin !== self.location.origin) return

  /*
   * The event stream is never intercepted.
   *
   * It is an infinite response: the network-first handler below would await
   * `fetch()` and then hold a response that never completes, and any attempt
   * to cache it would buffer forever. Falling through to the browser lets
   * EventSource own the connection, including its own reconnect.
   */
  if (url.pathname === `${BASE}api/events`) return

  // Listening before importing: a range stream proxied from YouTube, never
  // worth caching, and the browser owns its connection best (a seek drops it).
  if (url.pathname === `${BASE}api/import/listen`) return

  if (url.pathname.startsWith(`${BASE}api/stream/`)) {
    event.respondWith(handleAudio(request, url, event))
    return
  }

  if (url.pathname.startsWith(`${BASE}api/bucket/`)) {
    event.respondWith(bucketPicture(request, url))
    return
  }

  if (url.pathname.startsWith(`${BASE}api/art/`)) {
    event.respondWith(
      cacheFirst(request, API_CACHE, { key: coverKey(url), replaceOtherVersions: true }),
    )
    return
  }

  if (url.pathname.startsWith(`${BASE}api/`)) {
    event.respondWith(networkFirst(request))
    return
  }

  // The plain pages published beside the app (PLAIN_PAGES, by any of their
  // addresses: `privacy` or `privacy.html`, `install/` or its index file)
  // are not the app. Left to the browser, so loading one is never kept as the
  // app's offline index.
  const page = url.pathname.slice(BASE.length).replace(/(?:\/index)?\.html$|\/$/, '')
  if (Object.hasOwn(PLAIN_PAGES, page)) return

  event.respondWith(handleShell(request, url))
})

/**
 * Serve audio: from this device when it is here, from the bucket when it is not.
 *
 * A downloaded song is a complete 200 in the cache, and a player asking for
 * bytes 500-999 gets a correctly-formed 206 slice built here, because the
 * Cache API will not do it. A song that was never downloaded comes from the
 * bucket, once per play, and only the last few played are kept
 * (`playFromBucket`) — a library of a thousand songs is not something a
 * browser tab should quietly copy.
 */
async function handleAudio(request: Request, url: URL, event: FetchEvent): Promise<Response> {
  const cache = await caches.open(AUDIO_CACHE)
  const cacheKey = url.pathname

  /*
   * A download saying it wants fresh bytes gets them.
   *
   * `cache: 'reload'` only skips the browser's HTTP cache — this worker sits
   * in front of that and would hand back the copy the page is trying to
   * replace, so a song whose file changed on the server could never be refreshed
   * and every pass re-stored what it already had. The page asks with a header
   * rather than a query, since what is stored is keyed by path alone.
   */
  const wantsFresh = request.headers.get(REFRESH_HEADER) !== null
  // The page keeps a download under its whole stream address, `?v=` and all,
  // and the player may ask with another query: the path is what names a song.
  const cached = wantsFresh ? undefined : await cache.match(cacheKey, { ignoreSearch: true })

  if (cached) {
    const range = request.headers.get('range')
    if (!range) return cached
    return sliceResponse(cached, range)
  }

  const fromBucket = await bucketFileFor(url, 'audio')
  if (fromBucket) return playFromBucket(fromBucket, request, event)

  // Served by the server, and not on this device: go to the network and store
  // nothing. What this cache holds is the page's decision, never a side
  // effect of playing something (src/ports/offline.web.ts).
  try {
    return await fetch(request)
  } catch {
    return new Response('This song is not available offline.', {
      status: 503,
      statusText: 'Offline',
      headers: { 'Content-Type': 'text/plain' },
    })
  }
}

/** Whole downloads under way, by bucket key. */
const arriving = new Map<string, Arriving>()

/**
 * A cloud song, from the bucket: one download per play, kept for the next.
 *
 * Every range the player asked for was a request to the bucket, and the
 * bucket counts each against a daily allowance (docs/SYNC.md, "Caps"):
 * Safari's first two-byte look and the range after it, every seek past what
 * the player had buffered, and the whole song again on every replay once the
 * page had been reloaded. So the first request for a song starts one download
 * of the whole file, and every range — this one, the next, a seek — is read
 * from that download as it arrives. Once it is all here it is kept, under
 * the file's key, which is the hash of its bytes and so right for as long as
 * it is kept: the last `PLAYED_KEPT` songs, oldest first out. A replay, the
 * next song preloaded ahead of time, and a download the page makes of the
 * song are answered from the copy.
 *
 * A range that starts well past what has arrived — a song resumed half-way
 * through on a slow connection — is asked for as it is: one request more.
 */
async function playFromBucket(
  file: BucketFile,
  request: Request,
  event: FetchEvent,
): Promise<Response> {
  const range = request.headers.get('range')
  const cache = await caches.open(PLAYED_CACHE)
  const name = playedName(file.key)
  const kept = await cache.match(name)
  if (kept) return range ? sliceResponse(kept, range) : kept
  if (request.method === 'HEAD') return fetchFromBucket(file, range)

  let download = arriving.get(file.key)
  if (!download) {
    download = new Arriving(file, cache, name)
    arriving.set(file.key, download)
    // The worker stays up until the song is kept, whatever the player does meanwhile.
    event.waitUntil(download.kept)
  }
  const head = await download.head
  if (head.kind === 'refused') return download.refusal()

  const wanted = parseRange(range, head.size)
  if (wanted === null) return download.whole()
  if (wanted === 'unsatisfiable') return rangeNotSatisfiable(head.size)
  if (wanted.start > download.received + WAIT_AHEAD_BYTES) return fetchFromBucket(file, range)
  return download.slice(wanted.start, wanted.end)
}

/**
 * One song arriving from the bucket, whole, and readable from anywhere in it
 * while it does. Held in memory until it is all here — a song, a few
 * megabytes — then put in the cache and forgotten here.
 */
class Arriving {
  readonly head: Promise<{ kind: 'refused' } | { kind: 'ok'; size: number }>
  readonly kept: Promise<void>
  received = 0
  #chunks: Uint8Array[] = []
  #done = false
  #failed = false
  #response: Response | null = null
  /** The bucket's refusal, read once so each request waiting on it can be answered with it. */
  #refused: { status: number; headers: Headers; text: string } | null = null
  #wake: (() => void)[] = []

  constructor(file: BucketFile, cache: Cache, name: string) {
    const answered = fetchFromBucket(file)
    this.head = answered.then(async response => {
      this.#response = response
      const size = Number(response.headers.get('content-length') ?? Number.NaN)
      if (response.status === 200 && response.body && Number.isFinite(size) && size > 0) {
        return { kind: 'ok' as const, size }
      }
      const text = await response.text().catch(() => '')
      this.#refused = { status: response.status, headers: response.headers, text }
      return { kind: 'refused' as const }
    })
    this.kept = this.#read(cache, name)
      .catch(() => {
        // Stopped half-way, or a storage quota: the song played, and the next
        // play fetches it again.
        this.#failed = true
        this.#notify()
      })
      .finally(() => arriving.delete(file.key))
  }

  async #read(cache: Cache, name: string): Promise<void> {
    const head = await this.head
    const response = this.#response
    if (head.kind !== 'ok' || !response?.body) {
      this.#failed = true
      this.#notify()
      return
    }
    const reader = response.body.getReader()
    for (;;) {
      const { done, value } = await reader.read()
      if (done) break
      this.#chunks.push(value)
      this.received += value.byteLength
      this.#notify()
    }
    if (this.received !== head.size) throw new Error('the song stopped short')
    this.#done = true
    this.#notify()
    const headers = new Headers(response.headers)
    headers.set('Cache-Control', 'private, max-age=31536000, immutable')
    // The chunks stay: a range still streaming from this download reads them
    // until it closes, and the whole of it goes with the last one.
    await cache.put(
      name,
      new Response(new Blob(this.#chunks as BlobPart[]), { status: 200, headers }),
    )
    const names = await cache.keys()
    for (const old of names.slice(0, Math.max(0, names.length - PLAYED_KEPT))) {
      await cache.delete(old)
    }
    // The pages count a kept song as on this browser (src/ports/playedCopies.web.ts):
    // with the bucket refusing for the day, it is one of the few that still play.
    const clients = await self.clients.matchAll({ type: 'window' })
    for (const client of clients) client.postMessage({ type: SW_MESSAGE.played })
  }

  /** The bucket's own answer when it would not give the song: a cap's 502, say. */
  refusal(): Response {
    const refused = this.#refused
    return refused && refused.status !== 200
      ? new Response(refused.text, { status: refused.status, headers: refused.headers })
      : new Response('The song could not be fetched.', { status: 502 })
  }

  /** The whole song as it arrives, for the page keeping a copy. */
  async whole(): Promise<Response> {
    const head = await this.head
    if (head.kind !== 'ok') return this.refusal()
    const headers = new Headers({
      'Content-Type': this.#response?.headers.get('content-type') ?? 'audio/mp4',
      'Content-Length': String(head.size),
      'Accept-Ranges': 'bytes',
    })
    return new Response(this.#stream(0, head.size - 1), { status: 200, headers })
  }

  /** Bytes `start` to `end`, inclusive, as a 206 that streams as they arrive. */
  async slice(start: number, end: number): Promise<Response> {
    const head = await this.head
    if (head.kind !== 'ok') return this.refusal()
    const headers = new Headers({
      'Content-Type': this.#response?.headers.get('content-type') ?? 'audio/mp4',
      'Content-Length': String(end - start + 1),
      'Content-Range': `bytes ${start}-${end}/${head.size}`,
      'Accept-Ranges': 'bytes',
      'Cache-Control': 'no-store',
    })
    return new Response(this.#stream(start, end), {
      status: 206,
      statusText: 'Partial Content',
      headers,
    })
  }

  #stream(start: number, end: number): ReadableStream<Uint8Array> {
    let at = start
    return new ReadableStream<Uint8Array>({
      pull: async controller => {
        while (at > end || this.received <= at) {
          if (at > end) {
            controller.close()
            return
          }
          if (this.#failed || this.#done) {
            controller.error(new Error('the song stopped arriving'))
            return
          }
          await new Promise<void>(resolve => this.#wake.push(resolve))
        }
        const bytes = this.#bytes(at, Math.min(end, this.received - 1))
        at += bytes.byteLength
        controller.enqueue(bytes)
        if (at > end) controller.close()
      },
    })
  }

  /** The bytes from `from` to `to`, inclusive, out of the chunks that hold them. */
  #bytes(from: number, to: number): Uint8Array {
    const out = new Uint8Array(to - from + 1)
    let offset = 0
    let filled = 0
    for (const chunk of this.#chunks) {
      const chunkEnd = offset + chunk.byteLength
      if (chunkEnd > from && offset <= to) {
        const begin = Math.max(from, offset) - offset
        const stop = Math.min(to + 1, chunkEnd) - offset
        out.set(chunk.subarray(begin, stop), filled)
        filled += stop - begin
      }
      offset = chunkEnd
      if (offset > to) break
    }
    return out
  }

  #notify(): void {
    const waiting = this.#wake
    this.#wake = []
    for (const resolve of waiting) resolve()
  }
}

/** Where a played song is kept: under the worker's own scope, by its bucket key. */
function playedName(key: string): string {
  return new URL(`${PLAYED_PREFIX}${key}`, self.registration.scope).href
}

/**
 * Build a 206 Partial Content response from a complete cached one.
 *
 * Which bytes is packages/shared's `parseRange`, the rule the server and the
 * desktop shell answer `Range:` by: a header that is not one byte range —
 * `bytes=-` among them — is answered with the whole file, as they answer it.
 *
 * Through a blob, not an array buffer: a player asks for a song a range at a
 * time, and reading the whole file into this worker's memory for each range
 * would be a song's worth of copying per seek. A cached response's blob is
 * backed by the cache on disk, and slicing it copies nothing until the bytes
 * are read.
 */
async function sliceResponse(response: Response, rangeHeader: string): Promise<Response> {
  // Not a range at all: the whole file, without reading it here.
  if (relayedRange(rangeHeader) === null) return response
  const blob = await response.blob()
  const size = blob.size
  const wanted = parseRange(rangeHeader, size)
  if (wanted === null) return new Response(blob, response)
  if (wanted === 'unsatisfiable') return rangeNotSatisfiable(size)
  const { start, end } = wanted

  const headers = new Headers()
  headers.set('Content-Type', response.headers.get('content-type') ?? 'audio/mp4')
  headers.set('Content-Length', String(end - start + 1))
  headers.set('Content-Range', `bytes ${start}-${end}/${size}`)
  headers.set('Accept-Ranges', 'bytes')
  headers.set('Cache-Control', 'private, max-age=31536000, immutable')

  return new Response(blob.slice(start, end + 1), {
    status: 206,
    statusText: 'Partial Content',
    headers,
  })
}

function rangeNotSatisfiable(size: number): Response {
  return new Response(null, {
    status: 416,
    statusText: 'Range Not Satisfiable',
    headers: { 'Content-Range': `bytes */${size}` },
  })
}

/**
 * API requests: the network, and an honest "offline" when it is not there.
 *
 * Nothing is kept — not even the library, which the page already saves in
 * IndexedDB (src/offline/caches.ts). A second copy here, served
 * stale as a 200 when the server is away, tells the page it was answered when it
 * was not; the page's own copy does that job and shows the copy for what it is.
 */
async function networkFirst(request: Request): Promise<Response> {
  try {
    return await fetch(request)
  } catch {
    return new Response(JSON.stringify({ error: 'offline', code: API_ERROR.offline }), {
      status: 503,
      headers: { 'Content-Type': 'application/json' },
    })
  }
}

/**
 * The address a cover is kept under: its own, less `palette`.
 *
 * The page reads a cover's colour through a second address with `&palette=1`
 * on the end (src/ports/coverPixels.web.ts), so that a browser's HTTP cache
 * does not hand a canvas the copy an `<img>` loaded without CORS. Here both
 * are one picture from one bucket file, answered from this worker either way;
 * kept as two entries of one path, each store would sweep the other
 * (`replaceOtherVersions`), and every song played would fetch its cover again.
 */
function coverKey(url: URL): string {
  const key = new URL(url.href)
  key.searchParams.delete('palette')
  return key.href
}

/**
 * Cache-first, keyed on the full URL including `?v=` — or on `key`, when the
 * request has an address of its own that names the same thing.
 *
 * With `replaceOtherVersions`, storing a response drops every other version
 * of the same path, so a cover that changes does not leave the old one behind
 * forever. The others go after the store, by their exact addresses: dropped
 * by path before the store, two requests for one cover that missed together
 * each swept before either had stored, and both versions stayed.
 *
 * A version is its `v`, not the whole query: a row asks for a cover at
 * `size=128` and the player bar for the same one at full size; if each store
 * swept out the other, the two would go back to the network in turn and a
 * row's cover would come in late every time the song played.
 */
async function cacheFirst(
  request: Request,
  cacheName: string,
  options: { key?: string; replaceOtherVersions?: boolean } = {},
): Promise<Response> {
  const key = options.key ?? request.url
  const cached = await caches.match(key)
  if (cached) return cached
  try {
    const fromBucket = await bucketFileFor(new URL(request.url), 'cover')
    // Unpacked by the page from a pack of covers, under the picture's own key:
    // that copy, rather than a read from the bucket and a second copy here.
    const unpacked = fromBucket ? await caches.match(bucketAddress(fromBucket.key)) : undefined
    if (unpacked) return unpacked
    const response = fromBucket ? await fetchFromBucket(fromBucket) : await fetch(request)
    if (response.ok) {
      const cache = await caches.open(cacheName)
      await cache.put(key, response.clone())
      if (options.replaceOtherVersions) {
        const asked = new URL(key).searchParams.get('v')
        const versions = await cache.keys(new URL(key).pathname, { ignoreSearch: true })
        await Promise.all(
          versions
            .filter(version => new URL(version.url).searchParams.get('v') !== asked)
            .map(v => cache.delete(v)),
        )
      }
    }
    return response
  } catch {
    return new Response(null, { status: 503 })
  }
}

/**
 * The app shell.
 *
 * Navigations always resolve to `index.html` so client-side routes work
 * offline — opening the app on `/stats` with no network must not 404.
 */
async function handleShell(request: Request, url: URL): Promise<Response> {
  const cache = await caches.open(SHELL_CACHE)

  /*
   * The network first, so a deploy shows up on the next open, but not for
   * long: a connection that hangs rather than fails is the kept page after a
   * moment (SHELL_WAIT_MS), not a white one for as long as the browser waits,
   * and so is a host answering with an error of its own. Its 404 is still
   * the network's answer: Pages serves a page under the app (`/stats`) as a
   * copy of the app's page with that status.
   *
   * What the network answers is not kept. The page kept at install is this
   * build's, and the files it names are in this cache; one fetched later may
   * be a newer build's, naming a bundle this cache has never seen — opened
   * offline, a blank page. A newer build brings a new worker, which keeps its
   * own page.
   */
  if (request.mode === 'navigate') {
    const network = fetch(request).then(response => {
      if (response.status >= 500) throw new Error(`the page answered ${response.status}`)
      return response
    })
    const kept = await cache.match(INDEX)
    try {
      return await answerWithin(network, kept, SHELL_WAIT_MS)
    } catch {
      return new Response('Offline', { status: 503 })
    }
  }

  const cached = await cache.match(request)
  if (cached) {
    // Refresh in the background so the next load has the new build, without
    // making this one wait for the network.
    void (async () => {
      try {
        const fresh = await fetch(request)
        if (fresh.ok) await cache.put(request, fresh)
      } catch {
        // Offline: the cached copy stays.
      }
    })()
    return cached
  }

  try {
    const response = await fetch(request)
    // Only cache our own build output, not arbitrary paths.
    const ownOutput =
      url.pathname.startsWith(`${BASE}_expo/`) ||
      url.pathname.startsWith(`${BASE}assets/`) ||
      url.pathname.startsWith(`${BASE}icons/`)
    if (response.ok && ownOutput) {
      await cache.put(request, response.clone())
    }
    return response
  } catch {
    return new Response(null, { status: 503 })
  }
}

// --- The bucket, for the web build --------------------------------------------

/*
 * Where the app keeps the doorman session and each song's files: IndexedDB
 * (`DB_NAME` in ./names.ts), under the keys packages/replica writes them with
 * (`CLOUD_SESSION_KEY`, `CLOUD_FILES_KEY` in packages/shared).
 */

interface BucketFile {
  /** `audio/<sha256>.m4a`: the bytes, for good. */
  readonly key: string
  readonly url: string
  readonly token: string
}

/** How often, and how far apart, the map is read again for a key that does not match its address. */
const MAP_REREADS = 3
const MAP_REREAD_MS = 400

/**
 * The bucket file behind a stream or cover URL, when the app is signed in to
 * the doorman — which only the web build is. Null otherwise: served by the
 * server, nothing here changes.
 *
 * The address itself says which file it means. A library read from the
 * bucket gives a song's `rev` as `<audio hash>.<cover hash>`, the first twelve
 * characters of each file's hash-named key (packages/replica/src/
 * snapshotLibrary.ts, `hashOf`), and the page sends it as `?v=`. The map of
 * songs to keys read here is only the way from that to the whole key, and it
 * can lag: the page writes it to IndexedDB after it has drawn the library,
 * and the copy kept here is trusted for a few seconds. When a cover changed,
 * a row asking for the new address inside that lag would be answered with the
 * old file, and the cache would keep that answer under the new address for
 * good — one song wearing another's cover. So a key that does not
 * name what the address names is read again, a little later, a few times;
 * one that still does not is no answer at all, and nothing is stored.
 */
async function bucketFileFor(url: URL, kind: 'audio' | 'cover'): Promise<BucketFile | null> {
  if (!CLOUD) return null
  const match = /\/api\/(?:stream|art)\/(\d+)$/.exec(url.pathname)
  const songId = match?.[1]
  if (!songId) return null
  const wanted = keyHashIn(url, kind)
  try {
    let read = await bucketRead(false)
    // A song added a moment ago, or a session just made: not a miss yet.
    if (!read.fresh && (!read.session || read.files?.[songId] === undefined)) {
      read = await bucketRead(true)
    }
    let key = read.files?.[songId]?.[kind]
    for (let attempt = 0; wanted !== null && !names(key, wanted); attempt++) {
      if (attempt === MAP_REREADS) return null
      if (attempt > 0 || read.fresh) await pause(MAP_REREAD_MS)
      read = await bucketRead(true)
      key = read.files?.[songId]?.[kind]
    }
    if (!read.session || typeof key !== 'string') return null
    return {
      key,
      url: `${read.session.doormanUrl}${DOORMAN_PATHS.file(key)}`,
      token: read.session.token,
    }
  } catch {
    return null
  }
}

/** Where a bucket picture is kept by its key: the address `bucketPicture` answers. */
function bucketAddress(key: string): string {
  return new URL(`${BASE}api/bucket/${key}`, self.location.origin).href
}

/** `api/bucket/covers/<sha256>.<ext>`: the only bucket files asked for by key. */
const BUCKET_PICTURE_PATH = new RegExp(`/api/bucket/(covers/${HASH_FILE_NAME})$`)

/**
 * A bucket picture no song id names — an artist's — by its key
 * (src/ports/bucketMedia.web.ts, `bucketPictureAddress`). The key is the hash
 * of the bytes, so what is kept under it is right for good, and there is no
 * map to look it up in, nor one to lag.
 */
async function bucketPicture(request: Request, url: URL): Promise<Response> {
  const cached = await caches.match(request)
  if (cached) return cached
  const key = BUCKET_PICTURE_PATH.exec(url.pathname)?.[1]
  if (!CLOUD || !key) return new Response(null, { status: 404 })
  try {
    let read = await bucketRead(false)
    if (!read.session && !read.fresh) read = await bucketRead(true)
    if (!read.session) return new Response(null, { status: 404 })
    const response = await fetchFromBucket({
      key,
      url: `${read.session.doormanUrl}${DOORMAN_PATHS.file(key)}`,
      token: read.session.token,
    })
    if (response.ok) await (await caches.open(API_CACHE)).put(request, response.clone())
    return response
  } catch {
    return new Response(null, { status: 503 })
  }
}

/**
 * The twelve hex characters the address's `?v=` gives for `kind`'s key, or
 * null for an address that names no key: a song with no cover (`0` there),
 * or a server's addresses, whose `rev` is the file's size, mtime and art
 * revision in base 36 and never twelve hex characters.
 */
function keyHashIn(url: URL, kind: 'audio' | 'cover'): string | null {
  const rev = url.searchParams.get('v')
  if (!rev) return null
  const [audio = '', cover = ''] = rev.split('.')
  const half = kind === 'audio' ? audio : cover
  return /^[0-9a-f]{12}$/.test(half) ? half : null
}

/** Whether a bucket key is the file an address's hash names. */
function names(key: unknown, hash: string): boolean {
  return typeof key === 'string' && key.includes(`/${hash}`)
}

function pause(ms: number): Promise<void> {
  return new Promise(resolve => setTimeout(resolve, ms))
}

/**
 * How long the session and the song files read from IndexedDB are trusted.
 *
 * Every range the player asks for, and every cover, comes through
 * bucketFileFor, which otherwise opens the database twice and copies the whole
 * library's file map out of it per request, all through a song. Kept this
 * long, a file changed on another device or a token renewed is picked up
 * within seconds; an id not in the map at all is read again at once.
 */
const BUCKET_READ_MS = 5_000

interface BucketRead {
  readonly session: { doormanUrl: string; token: string } | null
  readonly files: Record<string, { audio?: unknown; cover?: unknown } | undefined> | null
  readonly at: number
}

let lastBucketRead: BucketRead | null = null

async function bucketRead(force: boolean): Promise<BucketRead & { fresh: boolean }> {
  const kept = lastBucketRead
  if (!force && kept && Date.now() - kept.at < BUCKET_READ_MS) return { ...kept, fresh: false }
  const [session, files] = await readStored([CLOUD_SESSION_KEY, CLOUD_FILES_KEY])
  const stored = session as { doormanUrl?: unknown; token?: unknown } | null
  lastBucketRead = {
    session:
      typeof stored?.doormanUrl === 'string' && typeof stored.token === 'string'
        ? { doormanUrl: stored.doormanUrl, token: stored.token }
        : null,
    files: typeof files === 'object' && files !== null ? (files as BucketRead['files']) : null,
    at: Date.now(),
  }
  return { ...lastBucketRead, fresh: true }
}

/**
 * The bucket refusing for the day (docs/SYNC.md, "Caps").
 *
 * Backblaze stops answering once a day's reads pass the account's cap, and the
 * doorman says so as a 502 with this code. Nothing this worker is asked for
 * will be answered until the cap is raised or the day turns, so for a while
 * the bucket is not asked: every cover a row draws and every range a player
 * wants is answered with the doorman's own refusal, from here. For as long as
 * the page's own hold lasts (`BUCKET_HOLD_MS`), then one more real request
 * finds out whether it is over — a cap raised at backblaze.com should not
 * have to wait for midnight to be noticed. The page is told
 * (`SW_MESSAGE.bucketCapped`, src/ports/serviceWorker.web.ts), so its own
 * reads — the snapshot, the words — stop too, and it can say why.
 *
 * In memory only: this worker is stopped when idle, and a wake costs one
 * refused request to learn it again, which is fine.
 */
let capped: { readonly until: number; readonly body: string } | null = null

/** The doorman's refusal, as the message the page shows and the body a player is answered with. */
function capMessage(body: string): string | null {
  const refusal = parseDoormanRefusal(body)
  return refusal?.code === BUCKET_CAP_CODE ? refusal.error : null
}

function refused(body: string): Response {
  return new Response(body, {
    status: 502,
    statusText: 'Bad Gateway',
    headers: { 'Content-Type': 'application/json', 'Cache-Control': 'no-store' },
  })
}

async function holdBucket(body: string, message: string): Promise<void> {
  capped = { until: Date.now() + BUCKET_HOLD_MS, body }
  const clients = await self.clients.matchAll({ type: 'window' })
  for (const client of clients) client.postMessage({ type: SW_MESSAGE.bucketCapped, message })
}

/**
 * A file from the bucket, as a plain same-origin response.
 *
 * A range asked for here is asked of the bucket too, and its answer — a 206,
 * a `content-range` — comes back as it is, so a song plays and seeks while it
 * arrives instead of after it. The bytes are passed straight on: the doorman
 * never holds a body whole, and neither does this.
 */
async function fetchFromBucket(file: BucketFile, range?: string | null): Promise<Response> {
  if (capped !== null) {
    if (Date.now() < capped.until) return refused(capped.body)
    capped = null
  }
  try {
    const ask = new Headers({ Authorization: `Bearer ${file.token}` })
    if (range) ask.set('range', range)
    const response = await fetch(file.url, { headers: ask })
    if (response.status === 502) {
      // The doorman's refusals are small JSON; a cap is the one worth holding.
      const body = await response.clone().text()
      const message = capMessage(body)
      if (message !== null) await holdBucket(body, message)
    }
    const headers = new Headers()
    for (const name of [
      'content-type',
      'content-length',
      'content-range',
      'accept-ranges',
      'etag',
    ]) {
      const value = response.headers.get(name)
      if (value) headers.set(name, value)
    }
    // A whole file is the one the hash names, forever. A slice of one is the
    // player's business for as long as it is playing, and no cache's; nor is
    // a refusal.
    headers.set(
      'Cache-Control',
      response.status === 206 || !response.ok ? 'no-store' : 'private, max-age=31536000, immutable',
    )
    return new Response(response.body, { status: response.status, headers })
  } catch {
    return new Response('This song is not on this device, and your storage cannot be reached.', {
      status: 503,
      statusText: 'Offline',
      headers: { 'Content-Type': 'text/plain', [UNANSWERED_HEADER]: '1' },
    })
  }
}

/** Several keys, in one opening of the database and one transaction. */
function readStored(keys: readonly string[]): Promise<unknown[]> {
  return new Promise((resolve, reject) => {
    const open = indexedDB.open(DB_NAME, DB_VERSION)
    open.onupgradeneeded = () => {
      if (!open.result.objectStoreNames.contains(DB_STORE)) open.result.createObjectStore(DB_STORE)
    }
    open.onerror = () => reject(open.error ?? new Error('could not open IndexedDB'))
    // Another tab holding an older version open keeps this one waiting: an
    // answer, not a hang.
    open.onblocked = () => reject(new Error('IndexedDB is open elsewhere at an older version'))
    open.onsuccess = () => {
      const db = open.result
      if (!db.objectStoreNames.contains(DB_STORE)) {
        db.close()
        resolve(keys.map(() => null))
        return
      }
      const transaction = db.transaction(DB_STORE, 'readonly')
      const store = transaction.objectStore(DB_STORE)
      const requests = keys.map(key => store.get(key))
      transaction.oncomplete = () => {
        db.close()
        resolve(requests.map(request => (request.result as unknown) ?? null))
      }
      // A transaction that errors or is aborted settles here too; left
      // unhandled, the promise would wait forever.
      const failed = (fallback: string) => () => {
        db.close()
        reject(transaction.error ?? new Error(fallback))
      }
      transaction.onerror = failed('IndexedDB read failed')
      transaction.onabort = failed('IndexedDB read aborted')
    }
  })
}

