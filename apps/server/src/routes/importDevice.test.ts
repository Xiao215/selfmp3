import { execFileSync } from 'node:child_process'
import crypto from 'node:crypto'
import fs from 'node:fs'
import http from 'node:http'
import type { AddressInfo } from 'node:net'
import os from 'node:os'
import path from 'node:path'
import { afterAll, beforeAll, describe, expect, it } from 'vitest'
import {
  IMPORT_META_HEADER,
  IMPORT_SHA256_HEADER,
  ImportEnqueueResultSchema,
  ImportQueueSchema,
  type ImportJob,
} from '@selfmp3/shared'
import { createApp } from '../app.js'
import { loadConfig, type ServingConfig } from '../config.js'
import { createContainer, type Container } from '../container.js'

/**
 * A song a device downloaded, end to end on the server
 * (docs/features/client-download.md): an import that asks for it, the lease,
 * the file and what is refused, and the song the file becomes — tagged as
 * yt-dlp would have tagged it, in the library and up in the bucket.
 *
 * The file is made by ffmpeg and measured by ffprobe, as a real one is, so
 * this needs both and is skipped without them.
 */

function hasFfmpeg(): boolean {
  try {
    execFileSync('ffmpeg', ['-version'], { stdio: 'ignore' })
    execFileSync('ffprobe', ['-version'], { stdio: 'ignore' })
    return true
  } catch {
    return false
  }
}

/** An m4a of `seconds` of tone, as a device would send one: untagged. */
function tone(dir: string, seconds: number): Buffer {
  const file = path.join(dir, `tone-${seconds}.m4a`)
  execFileSync('ffmpeg', [
    ...['-hide_banner', '-loglevel', 'error', '-y'],
    ...['-f', 'lavfi', '-i', `sine=frequency=440:duration=${seconds}`, '-c:a', 'aac', file],
  ])
  return fs.readFileSync(file)
}

const DESCRIPTION = `Provided to YouTube by JVR Music International Ltd.

晴天 · 周杰倫

葉惠美

℗ JVR MUSIC INTERNATIONAL LTD.

Released on: 2003-07-29

Auto-generated by YouTube.`

describe.skipIf(!hasFfmpeg())('a song a device downloaded', { timeout: 60_000 }, () => {
  const variables = [
    'SELFMP3_DATA_DIR',
    'SELFMP3_LIBRARY_DIR',
    'SELFMP3_LOG_LEVEL',
    'SELFMP3_CLOUD_DIR',
  ] as const
  const saved = new Map<string, string | undefined>()
  let root = ''
  let config: ServingConfig
  let container: Container
  let server: http.Server
  let origin = ''

  beforeAll(async () => {
    for (const name of variables) saved.set(name, process.env[name])
    root = fs.mkdtempSync(path.join(os.tmpdir(), 'selfmp3-device-'))
    process.env['SELFMP3_DATA_DIR'] = path.join(root, 'data')
    process.env['SELFMP3_LIBRARY_DIR'] = path.join(root, 'library')
    process.env['SELFMP3_LOG_LEVEL'] = 'silent'
    // The API answers nothing without a bucket; a folder stands in for one.
    process.env['SELFMP3_CLOUD_DIR'] = 'bucket'

    container = createContainer(loadConfig())
    config = container.config
    // Nothing here should ask the internet for lyrics.
    container.settings.update({ autoFetchLyrics: false })

    server = http.createServer(createApp(container))
    await new Promise<void>(resolve => server.listen(0, '127.0.0.1', resolve))
    origin = `http://127.0.0.1:${(server.address() as AddressInfo).port}`
  })

  afterAll(async () => {
    container.importQueue.stop()
    await new Promise<void>(resolve => server.close(() => resolve()))
    container.close()
    fs.rmSync(root, { recursive: true, force: true })
    for (const [name, value] of saved) {
      if (value === undefined) delete process.env[name]
      else process.env[name] = value
    }
  })

  const call = (method: string, url: string, init: RequestInit = {}): Promise<Response> =>
    fetch(`${origin}/api${url}`, {
      method,
      ...init,
      headers: { Authorization: `Bearer ${config.authToken}`, ...init.headers },
    })

  const post = (url: string, body: unknown) =>
    call('POST', url, {
      headers: { 'content-type': 'application/json' },
      body: JSON.stringify(body),
    })

  const upload = (
    id: string,
    lease: string,
    bytes: Buffer,
    headers: Record<string, string> = {},
  ): Promise<Response> =>
    call('PUT', `/import/device/jobs/${id}/file?lease=${encodeURIComponent(lease)}`, {
      headers: {
        'content-type': 'audio/mp4',
        [IMPORT_SHA256_HEADER]: crypto.createHash('sha256').update(bytes).digest('hex'),
        [IMPORT_META_HEADER]: Buffer.from(
          JSON.stringify({ description: DESCRIPTION, durationSeconds: 3 }),
        ).toString('base64url'),
        ...headers,
      },
      body: bytes,
    })

  async function job(id: string): Promise<ImportJob | undefined> {
    const queue = ImportQueueSchema.parse(await (await call('GET', '/import/queue')).json())
    return queue.jobs.find(each => each.id === id)
  }

  async function until(done: () => Promise<boolean>): Promise<void> {
    const deadline = Date.now() + 30_000
    while (!(await done())) {
      if (Date.now() > deadline) throw new Error('until: still false after 30s')
      await new Promise(resolve => setTimeout(resolve, 50))
    }
  }

  /** Every audio file the bucket holds. */
  function bucketAudio(): string[] {
    const found: string[] = []
    const walk = (dir: string): void => {
      for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
        const full = path.join(dir, entry.name)
        if (entry.isDirectory()) walk(full)
        else if (path.basename(dir) === 'audio' && entry.name.endsWith('.m4a')) found.push(full)
      }
    }
    walk(path.join(root, 'data'))
    return found
  }

  let lease = ''
  let jobId = ''

  it('holds an import’s YouTube songs for the device that asked', async () => {
    const response = await post('/import/enqueue', {
      items: [
        {
          url: 'https://music.youtube.com/watch?v=SJKoWAd5ySo',
          title: '晴天',
          artist: '周杰倫',
          album: '葉惠美',
          duration: 3,
        },
      ],
      fetchOnDevice: true,
    })
    expect(response.status).toBe(200)
    const result = ImportEnqueueResultSchema.parse(await response.json())
    expect(result.device?.jobIds).toEqual([result.jobs[0]?.id])
    lease = result.device?.lease ?? ''
    jobId = result.jobs[0]?.id ?? ''

    // The server leaves it alone: still waiting, a moment later.
    await new Promise(resolve => setTimeout(resolve, 200))
    expect(await job(jobId)).toMatchObject({ status: 'queued', step: 'waiting' })
  })

  it('follows the device’s download', async () => {
    expect((await post('/import/device/start', { lease, id: jobId })).status).toBe(200)
    const renewed = await post('/import/device/renew', {
      lease,
      progress: [{ id: jobId, percent: 40 }],
    })
    expect(await renewed.json()).toEqual({ held: [jobId] })
    expect(await job(jobId)).toMatchObject({ status: 'running', step: 'downloading', progress: 40 })
  })

  it('refuses a file that is not the song', async () => {
    const song = tone(root, 3)
    expect((await upload(jobId, 'not-the-lease', song)).status).toBe(409)
    expect((await upload(jobId, lease, song, { 'content-type': 'audio/webm' })).status).toBe(415)
    expect(
      (await upload(jobId, lease, song, { [IMPORT_SHA256_HEADER]: '0'.repeat(64) })).status,
    ).toBe(400)
    // Thirty seconds of something is not a three-second song.
    expect((await upload(jobId, lease, tone(root, 30))).status).toBe(422)
    // Each refusal leaves the job the device's.
    expect(await (await post('/import/device/renew', { lease })).json()).toEqual({ held: [jobId] })
  })

  it('makes the file a song, tagged as the review said, and puts it in the bucket', async () => {
    const response = await upload(jobId, lease, tone(root, 3))
    expect(response.status).toBe(202)
    await until(async () => (await job(jobId))?.status === 'done')

    const songId = (await job(jobId))?.songId ?? null
    expect(songId).not.toBeNull()
    expect(container.songs.byId(songId ?? 0)).toMatchObject({
      title: '晴天',
      artist: '周杰倫',
      album: '葉惠美',
      sourceUrl: 'https://music.youtube.com/watch?v=SJKoWAd5ySo',
      // Read back from the date the file was tagged with: when it came out, not when it went up.
      year: 2003,
    })

    const [audio] = bucketAudio()
    expect(audio).toBeDefined()
    const tags = JSON.parse(
      execFileSync('ffprobe', [
        '-v',
        'error',
        '-of',
        'json',
        '-show_entries',
        'format_tags',
        audio!,
      ]).toString(),
    ) as { format: { tags: Record<string, string> } }
    expect(tags.format.tags).toMatchObject({
      title: '晴天',
      artist: '周杰倫',
      album: '葉惠美',
      date: '2003-07-29',
    })
    // The job is the server's now: nothing left for the device to hold.
    expect(await (await post('/import/device/renew', { lease })).json()).toEqual({ held: [] })
  })

  it('downloads a song itself that the device let go', async () => {
    const result = ImportEnqueueResultSchema.parse(
      await (
        await post('/import/enqueue', {
          items: [
            { url: 'https://www.youtube.com/watch?v=dQw4w9WgXcQ', title: 'Never', duration: 3 },
          ],
          fetchOnDevice: true,
        })
      ).json(),
    )
    const held = result.device!
    const id = held.jobIds[0]!
    // The worker stopped first, so this test asks YouTube for nothing once the song is the server's.
    container.importQueue.stop()
    const released = await post('/import/device/release', {
      lease: held.lease,
      id,
      reason: 'no extension',
    })
    expect(released.status).toBe(200)
    expect(container.imports.fetcherOf(id)).toEqual({ fetcher: 'server', lease: null })
    expect(await job(id)).toMatchObject({ status: 'queued', step: 'waiting' })
    // Let go once is for good.
    expect((await post('/import/device/release', { lease: held.lease, id })).status).toBe(409)
  })
})
