/// <reference lib="webworker" />

/**
 * self.mp3 service worker.
 *
 * Three jobs, each with a deliberately different strategy:
 *
 *  1. **App shell** — kept whole at install, the page and every file it
 *     loads. The page is asked of the network for a moment first, so a new
 *     build shows up on the next open; past that moment, or offline, the kept
 *     one opens.
 *  2. **Audio** (./audio.ts) — cache-first, and critically it answers range
 *     requests out of the cache. Without that, iOS Safari will not play a
 *     cached file at all, because it always asks for `Range: bytes=0-1` first.
 *  3. **API** — the network, and an honest "offline" when it is not there;
 *     covers are kept, cache-first, and nothing else.
 *
 * Signed in to the cloud there is no server: a song or a cover this device
 * does not have yet is fetched from the bucket through the doorman instead,
 * with the session the app keeps in IndexedDB (./bucket.ts). A song is
 * downloaded whole once and every range is read from that download as it
 * arrives (./audio.ts, `playFromBucket`); the last few played are kept.
 *
 * The app may live under a path (`/selfmp3/` on Pages), so every path here is
 * taken relative to the scope this worker was registered with.
 *
 * Written by hand rather than generated by Workbox: the range-request handling
 * is the whole point of the worker and is not something a generic recipe does.
 */

import { API_ERROR, plainPageAt } from '@selfmp3/shared/wire'
import { API_CACHE, AUDIO_CACHE, CLOUD_FILES_CACHE, PLAYED_CACHE, SW_MESSAGE } from './names'
import { handleAudio } from './audio'
import {
  bucketAddress,
  bucketFileFor,
  bucketPicture,
  fetchFromBucket,
  releaseBucket,
} from './bucket'
import { SHELL_WAIT_MS, answerWithin } from '../src/ports/shellWait.model'

declare const self: ServiceWorkerGlobalScope

/**
 * A stamp the build replaces, so each build's shell is its own cache.
 *
 * The shell holds hashed asset files, which a new build renames rather than
 * overwrites: under one fixed cache name, every build's superseded JavaScript
 * and CSS would stay on the device for good. Naming the cache after the build
 * means `activate` sweeps the last one away as part of what it already does.
 * Left as `dev` when nothing substitutes it — one cache it keeps reusing.
 */
declare const __SHELL_BUILD__: string
const SHELL_BUILD = typeof __SHELL_BUILD__ === 'string' ? __SHELL_BUILD__ : 'dev'

const SHELL_CACHE = `selfmp3-shell-${SHELL_BUILD}`
/*
 * The API and audio caches (./names.ts) are deliberately *not* named after the
 * build: what they hold is the person's, not this build's, and re-downloading
 * every song and cover on a deploy is unthinkable.
 */

/**
 * Caches this worker keeps, its own and the tab's. Anything else from an old
 * build gets deleted.
 */
const OWNED_CACHES = new Set([SHELL_CACHE, API_CACHE, AUDIO_CACHE, CLOUD_FILES_CACHE, PLAYED_CACHE])

/** `/` in the desktop app, `/selfmp3/` on GitHub Pages: this worker's scope. */
const BASE = new URL(self.registration.scope).pathname

const INDEX = `${BASE}index.html`

/**
 * The files of this export the shell keeps besides the page, as paths under
 * the scope: written beside the worker by scripts/shell.mjs at export. Absent
 * for a worker built on its own, which then keeps the page alone.
 */
const SHELL_LIST = `${BASE}shell.json`

self.addEventListener('install', event => {
  event.waitUntil(
    (async () => {
      await keepShell()
      // Take over immediately; waiting for every tab to close is not the
      // behaviour anyone wants from their own music app.
      await self.skipWaiting()
    })(),
  )
})

/**
 * Keep this build's page and every file it loads, before taking over.
 *
 * All of it, at install. Kept as the page asked for them, the bundle was
 * never kept at all on a first visit (the page that loads it is not this
 * worker's yet) and, after a deploy, was kept by the old worker into the old
 * build's cache, which `activate` sweeps — either way the next offline open
 * was a blank page. A file that cannot be fetched fails the install, and the
 * browser tries again on a later visit: the worker before this one, and its
 * whole shell, stay until then.
 *
 * The page and the list are asked for past the browser's HTTP cache (Pages
 * says ten minutes), which would otherwise hand over the last build's page.
 * The rest are named after their contents, so a copy the last build kept is
 * the same file and is taken from there.
 */
async function keepShell(): Promise<void> {
  const cache = await caches.open(SHELL_CACHE)
  const fresh = (url: string) => new Request(url, { cache: 'no-cache' })
  await cache.add(fresh(INDEX))
  // Wanted, but not the app: a missing manifest does not fail the install.
  await cache.add(fresh(`${BASE}manifest.webmanifest`)).catch(() => undefined)
  const listed = await fetch(fresh(SHELL_LIST)).catch(() => null)
  const files: unknown = listed?.ok ? await listed.json() : []
  if (!Array.isArray(files)) return
  await Promise.all(
    files
      .filter((file): file is string => typeof file === 'string')
      .map(async file => {
        const url = `${BASE}${file}`
        const kept = await caches.match(url)
        await (kept ? cache.put(url, kept) : cache.add(url))
      }),
  )
}

self.addEventListener('activate', event => {
  event.waitUntil(
    (async () => {
      const names = await caches.keys()
      await Promise.all(
        names
          .filter(name => name.startsWith('selfmp3-') && !OWNED_CACHES.has(name))
          .map(name => caches.delete(name)),
      )
      await self.clients.claim()
    })(),
  )
})

self.addEventListener('message', event => {
  const data: unknown = event.data
  if (typeof data !== 'object' || data === null || !('type' in data)) return
  // A page loaded around this worker, by a hard reload, asking to be answered
  // for after all (src/ports/serviceWorker.web.ts).
  if (data.type === SW_MESSAGE.claim) event.waitUntil(self.clients.claim())
  if (data.type === SW_MESSAGE.release) releaseBucket()
})

self.addEventListener('fetch', event => {
  const request = event.request
  if (request.method !== 'GET' && request.method !== 'HEAD') return

  const url = new URL(request.url)
  // Never touch cross-origin requests (album art from a thumbnail host, etc).
  if (url.origin !== self.location.origin) return

  /*
   * The event stream is never intercepted.
   *
   * It is an infinite response: the network-first handler below would await
   * `fetch()` and then hold a response that never completes, and any attempt
   * to cache it would buffer forever. Falling through to the browser lets
   * EventSource own the connection, including its own reconnect.
   */
  if (url.pathname === `${BASE}api/events`) return

  // Listening before importing: a range stream proxied from YouTube, never
  // worth caching, and the browser owns its connection best (a seek drops it).
  if (url.pathname === `${BASE}api/import/listen`) return

  if (url.pathname.startsWith(`${BASE}api/stream/`)) {
    event.respondWith(handleAudio(request, url, event))
    return
  }

  if (url.pathname.startsWith(`${BASE}api/bucket/`)) {
    event.respondWith(bucketPicture(request, url))
    return
  }

  if (url.pathname.startsWith(`${BASE}api/art/`)) {
    event.respondWith(
      cacheFirst(request, API_CACHE, { key: coverKey(url), replaceOtherVersions: true }),
    )
    return
  }

  if (url.pathname.startsWith(`${BASE}api/`)) {
    event.respondWith(networkFirst(request))
    return
  }

  // The plain pages published beside the app (PLAIN_PAGES, by any of their
  // addresses: `privacy` or `privacy.html`, `install/` or its index file)
  // are not the app. Left to the browser, so loading one is never kept as the
  // app's offline index.
  if (plainPageAt(url.pathname.slice(BASE.length)) !== null) return

  event.respondWith(handleShell(request, url))
})

/**
 * API requests: the network, and an honest "offline" when it is not there.
 *
 * Nothing is kept — not even the library, which the page already saves in
 * IndexedDB (src/offline/caches.ts). A second copy here, served
 * stale as a 200 when the server is away, tells the page it was answered when it
 * was not; the page's own copy does that job and shows the copy for what it is.
 */
async function networkFirst(request: Request): Promise<Response> {
  try {
    return await fetch(request)
  } catch {
    return new Response(JSON.stringify({ error: 'offline', code: API_ERROR.offline }), {
      status: 503,
      headers: { 'Content-Type': 'application/json' },
    })
  }
}

/**
 * The address a cover is kept under: its own, less `palette`.
 *
 * The page reads a cover's colour through a second address with `&palette=1`
 * on the end (src/ports/coverPixels.web.ts), so that a browser's HTTP cache
 * does not hand a canvas the copy an `<img>` loaded without CORS. Here both
 * are one picture from one bucket file, answered from this worker either way;
 * kept as two entries of one path, each store would sweep the other
 * (`replaceOtherVersions`), and every song played would fetch its cover again.
 */
function coverKey(url: URL): string {
  const key = new URL(url.href)
  key.searchParams.delete('palette')
  return key.href
}

/**
 * Cache-first, keyed on the full URL including `?v=` — or on `key`, when the
 * request has an address of its own that names the same thing.
 *
 * With `replaceOtherVersions`, storing a response drops every other version
 * of the same path, so a cover that changes does not leave the old one behind
 * forever. The others go after the store, by their exact addresses: dropped
 * by path before the store, two requests for one cover that missed together
 * each swept before either had stored, and both versions stayed.
 *
 * A version is its `v`, not the whole query: a row asks for a cover at
 * `size=128` and the player bar for the same one at full size; if each store
 * swept out the other, the two would go back to the network in turn and a
 * row's cover would come in late every time the song played.
 */
async function cacheFirst(
  request: Request,
  cacheName: string,
  options: { key?: string; replaceOtherVersions?: boolean } = {},
): Promise<Response> {
  const key = options.key ?? request.url
  const cached = await caches.match(key)
  if (cached) return cached
  try {
    const fromBucket = await bucketFileFor(new URL(request.url), 'cover')
    // Unpacked by the page from a pack of covers, under the picture's own key:
    // that copy, rather than a read from the bucket and a second copy here.
    const unpacked = fromBucket ? await caches.match(bucketAddress(fromBucket.key)) : undefined
    if (unpacked) return unpacked
    const response = fromBucket ? await fetchFromBucket(fromBucket) : await fetch(request)
    if (response.ok) {
      const cache = await caches.open(cacheName)
      await cache.put(key, response.clone())
      if (options.replaceOtherVersions) {
        const asked = new URL(key).searchParams.get('v')
        const versions = await cache.keys(new URL(key).pathname, { ignoreSearch: true })
        await Promise.all(
          versions
            .filter(version => new URL(version.url).searchParams.get('v') !== asked)
            .map(v => cache.delete(v)),
        )
      }
    }
    return response
  } catch {
    return new Response(null, { status: 503 })
  }
}

/**
 * The app shell.
 *
 * Navigations always resolve to `index.html` so client-side routes work
 * offline — opening the app on `/stats` with no network must not 404.
 */
async function handleShell(request: Request, url: URL): Promise<Response> {
  const cache = await caches.open(SHELL_CACHE)

  /*
   * The network first, so a deploy shows up on the next open, but not for
   * long: a connection that hangs rather than fails is the kept page after a
   * moment (SHELL_WAIT_MS), not a white one for as long as the browser waits,
   * and so is a host answering with an error of its own. Its 404 is still
   * the network's answer: Pages serves a page under the app (`/stats`) as a
   * copy of the app's page with that status.
   *
   * What the network answers is not kept. The page kept at install is this
   * build's, and the files it names are in this cache; one fetched later may
   * be a newer build's, naming a bundle this cache has never seen — opened
   * offline, a blank page. A newer build brings a new worker, which keeps its
   * own page.
   */
  if (request.mode === 'navigate') {
    const network = fetch(request).then(response => {
      if (response.status >= 500) throw new Error(`the page answered ${response.status}`)
      return response
    })
    const kept = await cache.match(INDEX)
    try {
      return await answerWithin(network, kept, SHELL_WAIT_MS)
    } catch {
      return new Response('Offline', { status: 503 })
    }
  }

  const cached = await cache.match(request)
  if (cached) {
    // Refresh in the background so the next load has the new build, without
    // making this one wait for the network.
    void (async () => {
      try {
        const fresh = await fetch(request)
        if (fresh.ok) await cache.put(request, fresh)
      } catch {
        // Offline: the cached copy stays.
      }
    })()
    return cached
  }

  try {
    const response = await fetch(request)
    // Only cache our own build output, not arbitrary paths.
    const ownOutput =
      url.pathname.startsWith(`${BASE}_expo/`) ||
      url.pathname.startsWith(`${BASE}assets/`) ||
      url.pathname.startsWith(`${BASE}icons/`)
    if (response.ok && ownOutput) {
      await cache.put(request, response.clone())
    }
    return response
  } catch {
    return new Response(null, { status: 503 })
  }
}

export {}
