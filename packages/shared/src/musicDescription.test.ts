import { describe, expect, it } from 'vitest'
import { releaseOf } from './musicDescription.js'

/** What YouTube wrote under 晴天 (SJKoWAd5ySo), 2026-10-14. */
const QING_TIAN = `Provided to YouTube by JVR Music International Ltd.

晴天 · 周杰倫

葉惠美

℗ JVR MUSIC INTERNATIONAL LTD.

Released on: 2003-07-29

Auto-generated by YouTube.`

describe('releaseOf', () => {
  it('reads the day a YouTube Music track says it came out', () => {
    expect(releaseOf(QING_TIAN)).toEqual({ date: '2003-07-29', year: 2003 })
  })

  it('falls back to the ℗ year of an auto-generated track that names no day', () => {
    const text =
      'Provided to YouTube by X\n\nSong · Artist\n\nAlbum\n\n℗ 1975 EMI\n\nAuto-generated by YouTube.'
    expect(releaseOf(text)).toEqual({ date: null, year: 1975 })
  })

  it('reads nothing from a description someone wrote', () => {
    const text = 'REMASTERED IN HD!\nTaken from A Night At The Opera, 1975.\n℗ 1975 Queen'
    expect(releaseOf(text)).toEqual({ date: null, year: null })
  })

  it('reads nothing from nothing', () => {
    expect(releaseOf('')).toEqual({ date: null, year: null })
  })
})
