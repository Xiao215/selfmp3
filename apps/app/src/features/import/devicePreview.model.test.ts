import { describe, expect, it } from 'vitest'
import { toProbedTrack, type ThrottleState } from '@selfmp3/shared'
import {
  paceNote,
  previewOnDevice,
  refusing,
  singleVideo,
  takeTurn,
  type VideoFacts,
} from './devicePreview.model'

describe('singleVideo', () => {
  it.each([
    ['https://www.youtube.com/watch?v=SJKoWAd5ySo', 'https://www.youtube.com/watch?v=SJKoWAd5ySo'],
    ['https://youtu.be/SJKoWAd5ySo', 'https://www.youtube.com/watch?v=SJKoWAd5ySo'],
    [
      'https://music.youtube.com/watch?v=SJKoWAd5ySo',
      'https://www.youtube.com/watch?v=SJKoWAd5ySo',
    ],
    ['晴天 https://youtu.be/SJKoWAd5ySo', 'https://www.youtube.com/watch?v=SJKoWAd5ySo'],
  ])('takes %s as one video', (text, url) => {
    expect(singleVideo(text)).toBe(url)
  })

  it.each([
    'https://www.youtube.com/watch?v=SJKoWAd5ySo&list=PL1234567890',
    'https://www.youtube.com/playlist?list=PL1234567890',
    'https://music.youtube.com/search?q=yoasobi',
    'https://music.youtube.com/browse/MPREb_abcdefghijk',
    'https://www.youtube.com/@yoasobi',
    'https://music.163.com/song?id=186016',
    'https://youtu.be/SJKoWAd5ySo https://youtu.be/dQw4w9WgXcQ',
    'yoasobi idol',
  ])('leaves %s to the server', text => {
    expect(singleVideo(text)).toBeNull()
  })
})

const QING_TIAN: VideoFacts = {
  title: '晴天',
  author: 'Jay Chou - Topic',
  durationSeconds: 270,
  description: [
    'Provided to YouTube by JVR Music International Ltd.',
    '',
    '晴天 · 周杰倫',
    '',
    '葉惠美',
    '',
    '℗ JVR MUSIC INTERNATIONAL LTD.',
    '',
    'Released on: 2003-07-29',
    '',
    'Auto-generated by YouTube.',
  ].join('\n'),
  thumbnail: 'https://i.ytimg.com/vi/SJKoWAd5ySo/maxresdefault.jpg',
}

function deps(facts: VideoFacts | Error, have = false) {
  let budget: ThrottleState | null = null
  const asked: string[] = []
  return {
    asked,
    budget: () => budget,
    deps: {
      youtube: {
        describe: (url: string) => {
          asked.push(url)
          return facts instanceof Error ? Promise.reject(facts) : Promise.resolve(facts)
        },
      },
      alreadyHave: () => Promise.resolve({ have: [have], waiting: [false], queued: [false] }),
      budget: { get: () => budget, save: (state: ThrottleState) => (budget = state) },
      now: () => 1_700_000_000_000,
    },
  }
}

const URL = 'https://www.youtube.com/watch?v=SJKoWAd5ySo'

describe('previewOnDevice', () => {
  it('names a YouTube Music track by its credits, as yt-dlp would', async () => {
    const { deps: d } = deps(QING_TIAN)
    const preview = await previewOnDevice(d, URL)
    expect(preview).toMatchObject({ kind: 'single', playlistTitle: null, from: 'youtube' })
    expect(preview.items).toEqual([
      {
        url: URL,
        title: '晴天',
        artist: '周杰倫',
        album: '葉惠美',
        duration: 270,
        thumbnail: QING_TIAN.thumbnail,
        alreadyHave: false,
        waitingToUpload: false,
        inQueue: false,
        source: 'youtube',
        netease: null,
        youtube: null,
      },
    ])
  })

  it('names a plain video the way the server names one', async () => {
    const video: VideoFacts = {
      title: 'YOASOBI「アイドル」Official Music Video',
      author: 'Ayase / YOASOBI',
      durationSeconds: 213,
      description: 'Lyrics below',
      thumbnail: null,
    }
    const { deps: d } = deps(video)
    const [item] = (await previewOnDevice(d, URL)).items
    const server = toProbedTrack(
      { webpage_url: URL, title: video.title, uploader: video.author, duration: 213 },
      URL,
    )
    expect(item).toMatchObject({ title: server.title, artist: server.artist, album: '' })
  })

  it('says what the server says of the library', async () => {
    const { deps: d } = deps(QING_TIAN, true)
    expect((await previewOnDevice(d, URL)).items[0]?.alreadyHave).toBe(true)
  })

  it('keeps clear of YouTube after a refusal for rate, and gives up', async () => {
    const h = deps(new Error("Sign in to confirm you're not a bot"))
    await expect(previewOnDevice(h.deps, URL)).rejects.toThrow(/not a bot/)
    expect(h.budget()?.pausedUntil).toBeGreaterThan(1_700_000_000_000)
    // And the next look-up does not ask at all.
    await expect(previewOnDevice(h.deps, URL)).rejects.toThrow(/no turn/)
    expect(h.asked).toHaveLength(1)
  })
})

describe('takeTurn', () => {
  it('lets a person go a few turns ahead of the bucket, and then says no', () => {
    let budget: ThrottleState | null = null
    const store = { get: () => budget, save: (state: ThrottleState) => (budget = state) }
    const turns = Array.from({ length: 8 }, () => takeTurn(store, 1_700_000_000_000))
    expect(turns.filter(Boolean).length).toBeGreaterThan(0)
    expect(turns.at(-1)).toBe(false)
  })
})

describe('refusing', () => {
  it('is true only while a refusal for rate is still being waited out', () => {
    const at = (pausedUntil: number) => ({
      get: () => ({ tokens: 0, ratchet: 1, updatedAt: 0, pausedUntil, limitedAt: 0 }),
      save: () => undefined,
    })
    expect(refusing(at(2_000), 1_000)).toBe(true)
    expect(refusing(at(500), 1_000)).toBe(false)
    expect(refusing({ get: () => null, save: () => undefined }, 1_000)).toBe(false)
  })
})

describe('paceNote', () => {
  const state = (ratchet: number, pausedUntil: number) => ({
    tokens: 0,
    ratchet,
    updatedAt: 0,
    pausedUntil,
    limitedAt: 0,
  })

  it('says nothing at full pace', () => {
    expect(paceNote(null, 0)).toBeNull()
    expect(paceNote(state(1, 0), 1_000)).toBeNull()
  })

  it('says how far it was slowed, and how long it is still waiting', () => {
    expect(paceNote(state(0.5, 0), 1_000)).toMatch(/50%/)
    expect(paceNote(state(0.5, 1_000 + 10 * 60_000), 1_000)).toMatch(/50%.*10 min/)
    expect(paceNote(state(1, 1_000 + 30_000), 1_000)).toMatch(/1 min/)
  })
})
